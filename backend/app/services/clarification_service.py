"""Adaptive clarification engine (Phase 8).

Asks about the uncertain SPAN, never the whole sentence — unless the whole
sentence is what's uncertain. Questions are built deterministically from
stored evidence (engine disagreements, user correction patterns, language
ambiguity), never generated by an LLM: the options on screen must be
readings someone or something actually produced.

Interaction budget: at most MAX_QUESTIONS, blockers first. Grammar-only
diffs are never interrogated. Answering OR explicitly skipping resolves a
question — skipping preserves the uncertainty instead of hiding it.
High-impact blockers gate confirmation (overridable with explicit force).
"""
import re

MAX_QUESTIONS = 3
TRIVIAL = {"the", "a", "an", "is", "are", "was", "were", "be", "been", "am",
           ".", ",", "?", "!", "।"}


def _tokens(text: str) -> list[str]:
    return re.findall(r"[A-Za-z\u0900-\u097F']+", (text or "").lower())


def _trivial_diff(diff: dict) -> bool:
    toks = _tokens(diff.get("from", "")) + _tokens(diff.get("to", ""))
    return bool(toks) and all(t in TRIVIAL for t in toks)


def _qid(n: int) -> str:
    return f"q{n}"


def build_questions(transcript_text: str, evidence: dict, suggestion: dict | None,
                    patterns: list[dict], primary_provider: str, secondary_provider: str | None) -> list[dict]:
    """Pure builder. suggestion carries alternatives/needs_clarification/
    clarification_question/answers (may be None for transcript-direct)."""
    from .asr_orchestration import compare_transcripts

    ev = evidence or {}
    questions: list[dict] = []
    n = 0

    def add(target, question, options, severity, reason):
        nonlocal n
        n += 1
        questions.append({"id": _qid(n), "target": target, "question": question,
                          "options": options, "allows": ["select", "type", "saved_phrase", "skip"],
                          "severity": severity, "reason": reason})

    secondary_text = ev.get("secondary_text")
    primary = {"text": transcript_text, "language": "", "provider": primary_provider, "model_version": ""}
    comparison = compare_transcripts(primary, {"text": secondary_text or "", "language": "",
                                              "provider": secondary_provider or "",
                                              "model_version": ""} if secondary_text else None)
    divergence = comparison.get("meaning_divergence") or []
    if divergence and secondary_text:
        for problem in divergence[:2]:
            diffs = [d for d in comparison.get("word_diffs", []) if not _trivial_diff(d)][:1]
            if not diffs:
                continue
            d = diffs[0]
            add(f"'{d['from']}' vs '{d['to']}'",
                "These readings differ in meaning — which did you intend?",
                [{"id": f"q{n + 1}a", "label": d["from"], "source": f"{primary_provider} reading"},
                 {"id": f"q{n + 1}b", "label": d["to"], "source": f"{secondary_provider or 'second engine'} reading"}],
                "blocks_speech", f"engines disagree: {problem}")
            break  # one blocker per divergence set is enough to stop and ask

    toks = set(_tokens(transcript_text))
    seen_terms: set[str] = set()  # one question per ambiguous term
    for p in patterns:
        if len(questions) >= MAX_QUESTIONS:
            break
        if p["from"] not in toks or p["from"] in seen_terms:
            continue
        seen_terms.add(p["from"])
        # distinct readings for this term across the full pattern list
        readings = sorted({x["to"] for x in patterns if x["from"] == p["from"]})
        if len(readings) < 2:
            continue  # single stable reading needs no question
        add(f"the word '{p['from']}'",
            "You've corrected this word different ways — which one this time?",
            [{"id": f"q{n + 1}{chr(97 + i)}", "label": r, "source": "your past correction"}
             for i, r in enumerate(readings[:4])],
            "blocks_speech", "ambiguous personal pattern")

    indicators = ev.get("uncertainty", []) or []
    if len(questions) < MAX_QUESTIONS and any(i.get("kind") == "language_mismatch" for i in indicators):
        langs = sorted({s.get("lang", "?") for s in ev.get("language_spans", []) if s.get("lang")})
        if len(langs) >= 2:
            add("the language mix",
                "Which language should this be spoken in?",
                [{"id": f"q{n + 1}{chr(97 + i)}", "label": L, "source": "detected segment"}
                 for i, L in enumerate(langs[:3])],
                "advisory", "engines disagree on language")

    if (secondary_text and comparison.get("verdict") == "disagree"
            and len(questions) < MAX_QUESTIONS and not divergence):
        diffs = [d for d in comparison.get("word_diffs", []) if not _trivial_diff(d)][:2]
        for d in diffs:
            if len(questions) >= MAX_QUESTIONS:
                break
            add(f"'{d['from']}' vs '{d['to']}'", "Which wording did you say?",
                [{"id": f"q{n + 1}a", "label": d["from"], "source": f"{primary_provider} reading"},
                 {"id": f"q{n + 1}b", "label": d["to"], "source": f"{secondary_provider or 'second engine'} reading"}],
                "advisory", "wording differs between engines (meaning intact)")

    if not questions and suggestion and suggestion.get("needs_clarification"):
        add("the whole sentence",
            suggestion.get("clarification_question") or "Could you say the key word once more?",
            [], "advisory", "model asked for clarification without a targeted span")
    return questions[:MAX_QUESTIONS]


def unresolved_blockers(questions: list[dict], answers: dict | None) -> list[dict]:
    """Blockers neither answered nor explicitly skipped."""
    answers = answers or {}
    return [q for q in questions
            if q["severity"] == "blocks_speech" and q["id"] not in answers]


def apply_answer(question: dict, kind: str, value: str | None) -> dict:
    """Validate + record one answer. Raises ValueError on bad input."""
    if kind not in ("select", "type", "saved_phrase", "skip"):
        raise ValueError(f"unknown answer kind: {kind}")
    if kind == "skip":
        return {"kind": "skip", "value": None, "skipped": True,
                "note": "uncertainty preserved by explicit choice"}
    if kind == "select":
        options = {o["id"]: o["label"] for o in question.get("options", [])}
        if (value or "") not in options:
            raise ValueError("select value must be one of the offered option ids")
        return {"kind": "select", "value": value, "label": options[value], "skipped": False}
    if not (value or "").strip() or len(value) > 200:
        raise ValueError(f"{kind} needs 1–200 characters of text")
    return {"kind": kind, "value": value.strip(), "skipped": False}
